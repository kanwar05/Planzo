import PDFDocument from "pdfkit";
import Booking from "../models/Booking.js";
import Refund from "../models/Refund.js";
import User from "../models/User.js";
import Vendor from "../models/Vendor.js";
import ApiError from "../utils/ApiError.js";
import { getPaymentForCustomer } from "./paymentDomainService.js";

const same = (left, right) => String(left?._id || left || "") === String(right?._id || right || "");
const inr = paise => new Intl.NumberFormat("en-IN", {
  style: "currency", currency: "INR",
}).format(paise / 100);

function renderPdf(title, rows) {
  return new Promise((resolve, reject) => {
    const document = new PDFDocument({ size: "A4", margin: 52, info: { Title: title, Author: "Planzo" } });
    const chunks = [];
    document.on("data", chunk => chunks.push(chunk));
    document.once("error", reject);
    document.once("end", () => resolve(Buffer.concat(chunks)));
    document.fontSize(22).fillColor("#20201e").text("Planzo");
    document.moveDown(0.5).fontSize(18).text(title);
    document.moveDown(1);
    for (const [label, value] of rows) {
      document.fontSize(10).fillColor("#6b665f").text(label.toUpperCase());
      document.moveDown(0.2).fontSize(12).fillColor("#20201e").text(String(value ?? "—"));
      document.moveDown(0.7);
    }
    document.moveDown(1).fontSize(9).fillColor("#6b665f")
      .text("Generated by Planzo. This document does not include tax calculations or represent a GST tax invoice.");
    document.end();
  });
}

export async function createBookingInvoicePdf(bookingId, actor) {
  const booking = await Booking.findById(bookingId);
  if (!booking) throw new ApiError(404, "Booking not found.");
  if (actor.role !== "customer" || !same(booking.customerId, actor))
    throw new ApiError(403, "You cannot access this booking invoice.");
  const agreement = booking.acceptedAgreement;
  if (!agreement) throw new ApiError(409, "An invoice is available only for an accepted quotation.");
  const [customer, vendor] = await Promise.all([
    User.findById(booking.customerId).select("name"),
    Vendor.findById(booking.vendorId).select("businessName"),
  ]);
  const rows = [
    ["Invoice reference", `PL-${String(booking._id)}`],
    ["Booking reference", String(booking._id)],
    ["Issued", new Date().toISOString().slice(0, 10)],
    ["Customer", customer?.name || "Customer"],
    ["Vendor", vendor?.businessName || "Vendor"],
    ["Service", agreement.serviceDescription],
    ["Event date", booking.eventDateOnly],
    ...agreement.items.flatMap((item, index) => [
      [`Item ${index + 1}`, item.description],
      [`Item ${index + 1} amount`, inr(item.quantity * item.unitPriceAmount)],
    ]),
    ...agreement.additionalCharges.map((charge, index) => [`Additional charge ${index + 1}: ${charge.description}`, inr(charge.amount)]),
    ["Subtotal", inr(agreement.subtotalAmount)],
    ["Discount", inr(agreement.discountAmount)],
    ["Total due", inr(agreement.totalAmount)],
    ["Currency", "INR"],
    ["Terms", agreement.terms || "As stated in the accepted quotation."],
  ];
  return renderPdf("Booking invoice", rows);
}

export async function createPaymentReceiptPdf(paymentId, actor) {
  const payment = await getPaymentForCustomer(paymentId, actor);
  if (payment.capturedAmountPaise < 1)
    throw new ApiError(409, "A receipt is available only after payment capture.");
  const [booking, refunds] = await Promise.all([
    Booking.findById(payment.bookingId).select("eventType eventDateOnly"),
    Refund.find({ paymentId: payment._id, status: "processed" }).select("amountPaise"),
  ]);
  if (!booking) throw new ApiError(404, "Booking not found.");
  const refunded = refunds.reduce((total, item) => total + item.amountPaise, 0);
  return renderPdf("Payment receipt", [
    ["Receipt reference", `PR-${String(payment._id)}`],
    ["Booking reference", String(payment.bookingId)],
    ["Payment date", payment.updatedAt.toISOString().slice(0, 10)],
    ["Installment", payment.installment],
    ["Booking event", booking.eventType],
    ["Event date", booking.eventDateOnly],
    ["Amount captured", inr(payment.capturedAmountPaise)],
    ["Refunds processed", inr(refunded)],
    ["Net retained", inr(Math.max(0, payment.capturedAmountPaise - refunded))],
    ["Currency", payment.currency],
    ["Payment status", payment.status],
  ]);
}
